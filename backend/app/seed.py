def make_text_pdf(text: str) -> bytes:
    """Build a minimal single-page PDF containing the given text.

    Uses only the standard 14 fonts, so pypdf can always extract the text.
    This creates a REAL pdf file (not a stub) whose content is clearly
    synthetic.
    """
    # Escape parentheses/backslashes for PDF string literals; wrap at 90 cols.
    lines: list[str] = []
    for raw in text.split("\n"):
        while len(raw) > 90:
            lines.append(raw[:90])
            raw = raw[90:]
        lines.append(raw)
    content_parts = ["BT /F1 10 Tf 40 760 Td 12 TL"]
    for i, line in enumerate(lines):
        escaped = line.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")
        if i == 0:
            content_parts.append(f"({escaped}) Tj")
        else:
            content_parts.append(f"T* ({escaped}) Tj")
    content_parts.append("ET")
    stream = "\n".join(content_parts).encode("latin-1", errors="replace")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    ]

    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets: list[int] = []
    for idx, obj in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(f"{idx} 0 obj\n".encode())
        out.write(obj)
        out.write(b"\nendobj\n")
    xref_pos = out.tell()
    out.write(f"xref\n0 {len(objects) + 1}\n".encode())
    out.write(b"0000000000 65535 f \n")
    for off in offsets:
        out.write(f"{off:010d} 00000 n \n".encode())
    out.write(f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\n".encode())
    out.write(f"startxref\n{xref_pos}\n%%EOF".encode())
    return out.getvalue()


