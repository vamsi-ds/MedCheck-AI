def _store_document(db: Session, patient: Patient, doc_type: str, doc_date: date,
                    label: str, text: str) -> MedicalDocument:
    import hashlib
    import uuid

    from .config import UPLOAD_DIR

    pdf_bytes = make_text_pdf(text)
    stored_filename = f"{uuid.uuid4().hex}.pdf"
    path = UPLOAD_DIR / stored_filename
    path.write_bytes(pdf_bytes)
    doc = MedicalDocument(
        patient_id=patient.id,
        uploaded_by_user_id=None,
        original_filename=f"{label}.pdf",
        stored_filename=stored_filename,
        document_type=doc_type,
        mime_type="application/pdf",
        file_size=len(pdf_bytes),
        file_sha256=hashlib.sha256(pdf_bytes).hexdigest(),
        is_synthetic=True,
        processing_status=ProcessingStatus.completed,
        extraction_status=ExtractionStatus.succeeded,
        uploaded_at=utcnow(),
        document_date=doc_date,
    )
    db.add(doc)
    db.flush()
    db.add(ExtractedText(document_id=doc.id, text=text, method="seed", char_count=len(text)))
    return doc


